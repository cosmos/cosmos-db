// pebbleOptionsFile returns the OPTIONS file generated by Pebble for dir/name.db.
func pebbleOptionsFile(t *testing.T, dir, name string) string {
	t.Helper()
	paths, err := filepath.Glob(filepath.Join(dir, name+DBFileSuffix, "OPTIONS-*"))
	require.NoError(t, err)
	require.Len(t, paths, 1)
	bz, err := os.ReadFile(paths[0])
	require.NoError(t, err)
	return string(bz)
}

func TestNewPebbleDBWithOpts(t *testing.T) {
	dir := t.TempDir()
	cache := pebble.NewCache(64 << 20)
	defer cache.Unref()
	o := &pebble.Options{
		Cache:        cache,
		MemTableSize: 32 << 20,
		Levels:       make([]pebble.LevelOptions, 7),
	}
	for i := range o.Levels {
		o.Levels[i].FilterPolicy = bloom.FilterPolicy(10)
		o.Levels[i].TargetFileSize = 8 << 20
	}
	db, err := NewPebbleDBWithOpts("test", dir, o)
	require.NoError(t, err)

	opts := pebbleOptionsFile(t, dir, "test")
	require.Contains(t, opts, "cache_size=67108864")
	require.Contains(t, opts, "mem_table_size=33554432")
	require.Contains(t, opts, "filter_policy=rocksdb.BuiltinBloomFilter")
	require.Contains(t, opts, "target_file_size=8388608")
	require.Contains(t, opts, "max_concurrent_compactions=3")

	// The filter should answer Gets for missing keys within a table's key range.
	require.NoError(t, db.Set([]byte("a"), []byte{1}))
	require.NoError(t, db.Set([]byte("c"), []byte{3}))
	require.NoError(t, db.DB().Flush())
	value, err := db.Get([]byte("b"))
	require.NoError(t, err)
	require.Nil(t, value)
	require.Positive(t, db.DB().Metrics().Filter.Hits)

	require.NoError(t, db.Close())
}

func TestNewPebbleDBKeepsDefaults(t *testing.T) {
	dir := t.TempDir()
	open := func(name string, fn func() (DB, error)) string {
		db, err := fn()
		require.NoError(t, err)
		require.NoError(t, db.Close())
		return pebbleOptionsFile(t, dir, name)
	}

	plain := open("plain", func() (DB, error) { return NewPebbleDB("plain", dir, nil) })
	require.Contains(t, plain, "max_concurrent_compactions=3")
	require.Equal(t, plain, open("nil", func() (DB, error) { return NewPebbleDBWithOpts("nil", dir, nil) }))

	files := open("files", func() (DB, error) {
		return NewPebbleDB("files", dir, OptionsMap{"maxopenfiles": 100})
	})
	require.Contains(t, files, "max_open_files=100")
	require.Equal(t, files, open("opts", func() (DB, error) {
		return NewPebbleDBWithOpts("opts", dir, &pebble.Options{MaxOpenFiles: 100})
	}))
}

func TestPebbleDBIteratorAcrossClose(t *testing.T) {
	db, err := NewPebbleDBWithOpts("test", t.TempDir(), nil)
	require.NoError(t, err)
	require.NoError(t, db.Set([]byte("a"), []byte{1}))
	itr, err := db.Iterator(nil, nil)
	require.NoError(t, err)
	require.True(t, itr.Valid())

	require.NoError(t, db.Close())

	// Close happens after Valid, so subsequent iterator operations must not panic.
	require.Nil(t, itr.Key())
	require.Nil(t, itr.Value())
	itr.Next()
	require.False(t, itr.Valid())
	require.ErrorIs(t, itr.Error(), pebble.ErrClosed)
	require.NoError(t, itr.Close())

	_, err = db.Get([]byte("a"))
	require.ErrorIs(t, err, pebble.ErrClosed)
	_, err = db.Iterator(nil, nil)
	require.ErrorIs(t, err, pebble.ErrClosed)
	require.ErrorIs(t, db.NewBatch().Write(), pebble.ErrClosed)
	require.ErrorIs(t, db.Close(), pebble.ErrClosed)
}

// Close must wait for in-flight operations. Run with -race to verify.
func TestPebbleDBCloseWhileInUse(t *testing.T) {
	db, err := NewPebbleDBWithOpts("test", t.TempDir(), nil)
	require.NoError(t, err)
	for i := 0; i < 100; i++ {
		require.NoError(t, db.Set(int642Bytes(int64(i)), []byte{1}))
	}

	const workers = 8
	var started, done sync.WaitGroup
	started.Add(workers)
	done.Add(workers)
	for w := 0; w < workers; w++ {
		go func() {
			defer done.Done()
			err := readAndWrite(db)
			started.Done()
			for err == nil {
				err = readAndWrite(db)
			}
			if !errors.Is(err, pebble.ErrClosed) {
				t.Errorf("want pebble.ErrClosed, got %v", err)
			}
		}()
	}
	started.Wait()
	require.NoError(t, db.Close())
	done.Wait()
}

func readAndWrite(db DB) error {
	if _, err := db.Get(int642Bytes(1)); err != nil {
		return err
	}
	batch := db.NewBatch()
	defer batch.Close()
	if err := batch.Set(int642Bytes(1), []byte{2}); err != nil {
		return err
	}
	if err := batch.Write(); err != nil {
		return err
	}
	itr, err := db.Iterator(nil, nil)
	if err != nil {
		return err
	}
	defer itr.Close()
	for ; itr.Valid(); itr.Next() {
		_ = itr.Key()
		_ = itr.Value()
	}
	return itr.Error()
}
